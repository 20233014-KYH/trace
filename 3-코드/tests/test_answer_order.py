"""
test_answer_order.py — 붙여넣기 기록 없이 글자만 닮은 제안을 거르는 두 규칙 (11/16 김용현 맥 실제 시험)

  ① 답을 물어보기 전에 다 쳐 둔 문장은 그 답에서 올 수 없다 — 15:05 에 친 "20233014 김용현" 이 15:07 ChatGPT 답에 '보고 씀' 으로 제안됨
  ② 숫자를 빼면 아주 짧은 줄(학번 · 날짜)은 숫자 조각만 겹쳐도 잇지 않는다

  python 3-코드/tests/test_answer_order.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from core import match as M                      # noqa: E402

통과, 실패 = 0, 0


def 검사(이름, 조건, 덧=""):
    global 통과, 실패
    통과, 실패 = (통과 + 1, 실패) if 조건 else (통과, 실패 + 1)
    print(f"  {'✓' if 조건 else '✗'} {이름} {덧}")


답 = ("2025년 11월 연합뉴스 보도에서 인용한 대교협 조사에서는 131개 대학 중 30개교가 생성형 AI 활용 정책을 채택했습니다. "
      "2026년 2월 조사에서는 응답 대학 140개교 중 56개교로 늘었습니다.")
답들 = [{"id": "a1", "text": 답, "asked": "2026-11-16T15:07:00+09:00", "ts": "2026-11-16T15:08:00+09:00"}]
본문 = "대교협 조사에서는 131개 대학 중 30개교가 생성형 AI 활용 정책을 채택했다고 한다."    # 답을 보고 다시 친 문장


def 라벨(문단, 친글):
    proc = {"typed": [t for _, t in 친글], "typed_at": 친글, "noproc": []}
    return [r["label"] for row in M.link_document(문단, 답들, pasted=[], others=[], proc=proc) for r in row]


def main():
    print("\n  답보다 먼저 쓴 문장 · 숫자만 겹친 줄\n  " + "─" * 60)
    l = 라벨(["20233014 김용현"], [("2026-11-16T15:05:00+09:00", "20233014 김용현")])
    검사("① 답 전에 친 학번 줄 → 출처 기록 없음", l == ["none"], str(l))
    l = 라벨(["20233014 김용현"], [])
    검사("② 친 기록이 없어도 숫자만 겹친 짧은 줄 → 출처 기록 없음", l == ["none"], str(l))
    l = 라벨([본문], [("2026-11-16T15:10:00+09:00", 본문)])
    검사("답 뒤에 다시 친 문장은 그대로 '보고 씀'", l == ["viewed"], str(l))
    l = 라벨([본문], [("2026-11-16T15:01:00+09:00", 본문)])
    검사("답 전에 이미 다 쳐 둔 같은 문장 → 출처 기록 없음", l == ["none"], str(l))
    l = 라벨([본문], [("2026-11-16T15:01:00+09:00", 본문[:20]), ("2026-11-16T15:12:00+09:00", 본문[20:])])
    검사("일부라도 답 뒤에 쳤으면 막지 않음", l == ["viewed"], str(l))
    l = 라벨([본문], [])
    검사("친 기록이 없으면(옛 기록) 예전처럼", l == ["viewed"], str(l))
    print("  " + "─" * 60 + f"\n  {'✓ 통과' if not 실패 else '✗ 실패'}  ({통과}개 통과 · {실패}개 실패)\n")
    sys.exit(1 if 실패 else 0)


if __name__ == "__main__":
    main()
