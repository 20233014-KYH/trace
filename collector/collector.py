# =============================================
# Trace 수집기 — 2단계
#
# 하는 일 : 1초마다 두 가지를 확인하고, 바뀌었을 때만 한 줄 찍는다.
#           ① 지금 맨 앞에 뜬 프로그램이 바뀌었나
#           ② 뭔가 복사했나  (내용은 안 본다. 길이와 지문만)
#
# 아직 저장하지 않는다. 화면도 없다. 찍기만 한다.
#
# 실행 :  python collector.py
# 멈춤 :  Control + C
# =============================================

import platform          # 지금 맥인지 윈도우인지 알려주는 파이썬 기본 도구
import sys
import time


# ---------------------------------------------
# 1. 지금 컴퓨터가 맥인지 윈도우인지 보고, 맞는 파일을 불러온다
#
#    platform.system() 은 맥이면 "Darwin", 윈도우면 "Windows" 라고 답한다
#    ("Darwin" 은 맥 속에 들어 있는 엔진 이름이다)
# ---------------------------------------------
현재_운영체제 = platform.system()

if 현재_운영체제 == "Darwin":
    import platform_mac as os_layer
elif 현재_운영체제 == "Windows":
    import platform_win as os_layer
else:
    print(f"맥과 윈도우만 지원합니다. (지금: {현재_운영체제})")
    sys.exit(1)


# ---------------------------------------------
# 2. 계속 돌면서 확인한다
# ---------------------------------------------
def main():
    print()
    print("  Trace 수집기를 시작합니다.")
    print(f"  지금 컴퓨터: {현재_운영체제}")
    print("  창을 바꾸거나 뭔가 복사해 보세요.")
    print("  복사한 '내용'은 보지 않습니다. 길이와 지문만 적습니다.")
    print("  멈추려면 Control + C 를 누르세요.")
    print("  " + "─" * 58)

    직전_앱 = None            # 방금 전에 본 프로그램
    직전_복사번호 = None       # 방금 전에 본 클립보드 번호

    while True:               # 멈출 때까지 계속 반복
        시각 = time.strftime("%H:%M:%S")

        # ── ① 창이 바뀌었나 ──────────────────────
        지금_앱 = os_layer.active_app()

        if 지금_앱 != 직전_앱:
            이름 = 지금_앱["app"] or "(알 수 없음)"
            # 창 제목이 있으면 같이 찍는다 (윈도우는 있고, 맥은 보통 없다)
            제목 = f"  |  {지금_앱['title']}" if 지금_앱["title"] else ""
            print(f"  {시각}  [창]   {이름}{제목}")
            직전_앱 = 지금_앱

        # ── ② 뭔가 복사했나 ─────────────────────
        #
        #    평소에는 '번호'만 본다. 번호가 바뀌었을 때만 길이를 잰다.
        #    이렇게 해야 남의 클립보드를 1초마다 들여다보지 않게 된다.
        복사번호 = os_layer.clipboard_serial()

        if 직전_복사번호 is None:
            # 프로그램을 막 켠 순간. 켜기 전에 복사해 둔 것까지
            # 새로 복사한 것처럼 찍히면 안 되므로 번호만 기억하고 넘어간다.
            직전_복사번호 = 복사번호

        elif 복사번호 != 직전_복사번호:
            직전_복사번호 = 복사번호
            지문정보 = os_layer.clipboard_digest()

            if 지문정보["length"] is None:
                print(f"  {시각}  [복사]  글자가 아닌 것 (사진·파일 등)")
            else:
                짧은지문 = 지문정보["hash"][:12]      # 앞 12자만 보여준다
                print(f"  {시각}  [복사]  {지문정보['length']}글자   지문 {짧은지문}…")

        time.sleep(1)         # 1초 쉬었다가 다시 확인


# ---------------------------------------------
# 3. 이 파일을 직접 실행했을 때만 main() 을 돌린다
# ---------------------------------------------
if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:      # Control + C 를 누르면 여기로 온다
        print("\n  수집기를 멈췄습니다.\n")
