# =============================================
# Trace 수집기 — 3단계
#
# 하는 일 : 1초마다 두 가지를 확인하고, 바뀌었을 때만
#           ① 화면에 찍고  ② 파일에 남긴다.
#
#           ⓐ 지금 맨 앞에 뜬 프로그램이 바뀌었나
#           ⓑ 뭔가 복사했나    (내용은 안 본다. 길이와 지문만)
#           ⓒ 뭔가 붙여넣었나  (⌘V / Ctrl+V 를 눌렀나)
#
# 기록은 trace/data/sessions/ 안에 날짜 이름으로 쌓인다.
# 그 폴더는 깃에 올라가지 않는다. 내 컴퓨터에만 있다.
#
# 실행 :  python collector.py
# 멈춤 :  Control + C
# =============================================

import platform          # 지금 맥인지 윈도우인지 알려주는 파이썬 기본 도구
import sys
import time

import storage           # 옆에 있는 storage.py (기록 담당)


# ---------------------------------------------
# 1. 지금 컴퓨터가 맥인지 윈도우인지 보고, 맞는 파일을 불러온다
#
#    platform.system() 은 맥이면 "Darwin", 윈도우면 "Windows" 라고 답한다
#    ("Darwin" 은 맥 속에 들어 있는 엔진 이름이다)
# ---------------------------------------------
현재_운영체제 = platform.system()

if 현재_운영체제 == "Darwin":
    import platform_mac as os_layer
elif 현재_운영체제 == "Windows":
    import platform_win as os_layer
else:
    print(f"맥과 윈도우만 지원합니다. (지금: {현재_운영체제})")
    sys.exit(1)


# ---------------------------------------------
# 2. 계속 돌면서 확인한다
# ---------------------------------------------
def main():
    장부 = storage.기록장()        # ← 세션 파일이 여기서 만들어진다

    # 붙여넣기 감시를 켠다. 맥은 권한이 없으면 실패할 수 있다.
    붙여넣기_감시중 = os_layer.paste_watch_start()

    print()
    print("  Trace 수집기를 시작합니다.")
    print(f"  지금 컴퓨터: {현재_운영체제}")
    print(f"  기록 파일  : {장부.경로}")
    print("  창을 바꾸거나, 복사하거나, 붙여넣어 보세요.")
    print("  복사한 '내용'은 보지 않습니다. 길이와 지문만 적습니다.")

    if not 붙여넣기_감시중:
        안내 = os_layer.permission_hint()
        print()
        print("  ⚠️  " + (안내 or "붙여넣기 감시를 켜지 못했습니다."))
        print()

    print("  멈추려면 Control + C 를 누르세요.")
    print("  " + "─" * 58)

    장부.적기("watch_state", {"paste_watch": 붙여넣기_감시중})

    직전_앱 = None            # 방금 전에 본 프로그램
    직전_복사번호 = None       # 방금 전에 본 클립보드 번호

    try:
        while True:               # 멈출 때까지 계속 반복
            시각 = time.strftime("%H:%M:%S")

            # ── ⓐ 창이 바뀌었나 ──────────────────────
            지금_앱 = os_layer.active_app()

            if 지금_앱 != 직전_앱:
                직전_앱 = 지금_앱
                이름 = 지금_앱["app"] or "(알 수 없음)"

                줄지문 = 장부.적기("app", {
                    "app": 지금_앱["app"],
                    "title": 지금_앱["title"],
                })

                # 창 제목이 있으면 같이 찍는다 (윈도우는 있고, 맥은 보통 없다)
                제목 = f"  |  {지금_앱['title']}" if 지금_앱["title"] else ""
                print(f"  {시각}  [창]   {이름}{제목}   ·{줄지문[:8]}")

            # ── ⓑ 뭔가 복사했나 ─────────────────────
            #
            #    평소에는 '번호'만 본다. 번호가 바뀌었을 때만 길이를 잰다.
            #    이렇게 해야 남의 클립보드를 1초마다 들여다보지 않게 된다.
            복사번호 = os_layer.clipboard_serial()

            if 직전_복사번호 is None:
                # 프로그램을 막 켠 순간. 켜기 전에 복사해 둔 것까지
                # 새로 복사한 것처럼 찍히면 안 되므로 번호만 기억하고 넘어간다.
                직전_복사번호 = 복사번호

            elif 복사번호 != 직전_복사번호:
                직전_복사번호 = 복사번호
                지문정보 = os_layer.clipboard_digest()

                줄지문 = 장부.적기("clipboard", {
                    "length": 지문정보["length"],
                    "hash": 지문정보["hash"],      # 원문은 절대 넣지 않는다
                })

                if 지문정보["length"] is None:
                    print(f"  {시각}  [복사]  글자가 아닌 것 (사진·파일 등)   ·{줄지문[:8]}")
                else:
                    짧은지문 = 지문정보["hash"][:12]      # 앞 12자만 보여준다
                    print(f"  {시각}  [복사]  {지문정보['length']}글자   "
                          f"지문 {짧은지문}…   ·{줄지문[:8]}")

            # ── ⓒ 뭔가 붙여넣었나 ───────────────────
            #
            #    복사와 달리 붙여넣기는 클립보드를 바꾸지 않는다.
            #    그래서 키(⌘V / Ctrl+V)를 직접 봐야 한다.
            붙여넣기_횟수 = os_layer.paste_watch_poll()

            for _ in range(붙여넣기_횟수):
                # 붙여넣은 그 순간 클립보드에 뭐가 있었는지를 같이 적는다.
                # 이게 있어야 나중에 "아까 AI 탭에서 복사한 그것"과 맞춰볼 수 있다.
                지문정보 = os_layer.clipboard_digest()

                줄지문 = 장부.적기("paste", {
                    "length": 지문정보["length"],
                    "hash": 지문정보["hash"],      # 원문은 절대 넣지 않는다
                    "into": 지금_앱["app"],        # 어느 프로그램에 붙였나
                })

                어디 = 지금_앱["app"] or "(알 수 없음)"
                if 지문정보["length"] is None:
                    print(f"  {시각}  [붙임]  글자가 아닌 것 → {어디}   ·{줄지문[:8]}")
                else:
                    print(f"  {시각}  [붙임]  {지문정보['length']}글자   "
                          f"지문 {지문정보['hash'][:12]}…  → {어디}   ·{줄지문[:8]}")

            # 1초 쉬었다가 다시 확인.
            # time.sleep 이 아니라 os_layer.sleep 을 쓰는 이유 —
            # 그냥 자버리면 그 1초 사이에 누른 ⌘V 를 통째로 놓친다.
            os_layer.sleep(1)

    finally:
        # Control + C 를 누르든 오류가 나든, 파일은 반드시 닫는다.
        장부.닫기()
        print()
        print(f"  기록 {장부.줄번호}줄을 남겼습니다.")
        print(f"  {장부.경로}")
        print()
        print("  이 기록이 나중에 고쳐졌는지 확인하려면:")
        print(f"      python storage.py \"{장부.경로}\"")


# ---------------------------------------------
# 3. 이 파일을 직접 실행했을 때만 main() 을 돌린다
# ---------------------------------------------
if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:      # Control + C 를 누르면 여기로 온다
        print("  수집기를 멈췄습니다.\n")
