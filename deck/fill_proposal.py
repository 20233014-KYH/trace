def 글(도형, *줄들):
    """문단 수를 유지하면서 글자만 바꾼다 (서식 보존)."""
    tf = 도형.text_frame
    문단 = tf.paragraphs
    for i, p in enumerate(문단):
        새글 = 줄들[i] if i < len(줄들) else ""
        if p.runs:
            p.runs[0].text = 새글
            for r in p.runs[1:]:
                r.text = ""
        else:
            p.text = 새글


def 칸(표, r, c, 글자):
    셀 = 표.cell(r, c)
    p = 셀.text_frame.paragraphs[0]
    if p.runs:
        p.runs[0].text = 글자
        for x in p.runs[1:]:
            x.text = ""
    else:
        p.text = 글자
    for extra in 셀.text_frame.paragraphs[1:]:
        for x in extra.runs:
            x.text = ""


