def 찾기(슬라이드, 이름):
    for sh in 슬라이드.shapes:
        if sh.name == 이름:
            return sh
    raise KeyError(f"{이름} 없음")


def 표찾기(슬라이드, 번째=0):
    표들 = [sh.table for sh in 슬라이드.shapes if sh.has_table]
    return 표들[번째]


